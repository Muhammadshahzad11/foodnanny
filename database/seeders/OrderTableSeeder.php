                            'order_id'       => $transaction['order_id'],
                            'transaction_no' => $transaction['transaction_no'],
                            'amount'         => $transaction['amount'],
                            'payment_method' => $transaction['payment_method'],
                            'type'           => $transaction['type'],
                            'created_at'     => $transaction['created_at'],
                            'updated_at'     => $transaction['updated_at']
                        ]);
                    }
                };
                if (!empty($order['statements']) && is_array($order['statements'])) {
                    foreach ($order['statements'] as $statement) {
                        Statement::create([
                            'model_type' => $statement['model_type'],
                            'model_id'   => $statement['model_id'],
                            'date'       => $statement['date'],
                            'order_id'   => $statement['order_id'],
                            'type'       => $statement['type'],
                            'detail'     => $statement['detail'],
                            'sign'       => $statement['sign'],
                            'amount'     => $statement['amount'],
                            'info'       => $statement['info'],
                            'created_at' => $statement['created_at'],
                            'updated_at' => $statement['updated_at']
                        ]);
                    }
                };
                if (isset($order['orderPosDetail'])) {
                    OrderPosDetail::create([
                        'order_id'        => $order['orderPosDetail']['order_id'],
                        'payment_method'  => $order['orderPosDetail']['payment_method'],
                        'payment_note'    => $order['orderPosDetail']['payment_note'],
                        'received_amount' => $order['orderPosDetail']['received_amount'],
                        'created_at'      => $order['orderPosDetail']['created_at'],
                        'updated_at'      => $order['orderPosDetail']['updated_at']
                    ]);
                };
            }
        }
